-- =========================================================
-- Contact change (email / mobile) with OTP verification
-- Run once against payments_db (ddl-auto=validate will not create these)
-- =========================================================

-- When the customer last changed email/phone; drives the cooling-off period
ALTER TABLE customers ADD COLUMN contact_changed_at TIMESTAMP(6);

-- A mobile number can belong to only one customer
ALTER TABLE customers ADD CONSTRAINT uq_customers_phone_number UNIQUE (phone_number);

-- ---------- contact_change_requests ----------
CREATE TABLE contact_change_requests (
    request_id       BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    customer_id      BIGINT       NOT NULL,
    contact_type     VARCHAR(10)  NOT NULL,
    old_value        VARCHAR(255) NOT NULL,
    new_value        VARCHAR(255) NOT NULL,
    otp_hash         VARCHAR(100) NOT NULL,
    failed_attempts  INTEGER      NOT NULL DEFAULT 0,
    status           VARCHAR(20)  NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL,
    expires_at       TIMESTAMP(6) NOT NULL,
    completed_at     TIMESTAMP(6),

    CONSTRAINT pk_contact_change_requests       PRIMARY KEY (request_id),
    CONSTRAINT fk_contact_change_customer       FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id),
    CONSTRAINT ck_contact_change_type           CHECK (contact_type IN ('EMAIL', 'PHONE')),
    CONSTRAINT ck_contact_change_status         CHECK (status IN ('PENDING', 'VERIFIED', 'EXPIRED', 'FAILED', 'CANCELLED')),
    CONSTRAINT ck_contact_change_attempts       CHECK (failed_attempts >= 0)
);

CREATE INDEX idx_contact_change_customer_status ON contact_change_requests (customer_id, status);

-- ---------- customer_audit_log ----------
CREATE TABLE customer_audit_log (
    audit_id     BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    customer_id  BIGINT       NOT NULL,
    action       VARCHAR(30)  NOT NULL,
    old_value    VARCHAR(255),
    new_value    VARCHAR(255),
    changed_at   TIMESTAMP(6) NOT NULL,

    CONSTRAINT pk_customer_audit_log PRIMARY KEY (audit_id),
    CONSTRAINT fk_audit_customer     FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id),
    CONSTRAINT ck_audit_action       CHECK (action IN ('EMAIL_CHANGED', 'PHONE_CHANGED', 'CUSTOMER_DEACTIVATED'))
);

CREATE INDEX idx_audit_customer_changed_at ON customer_audit_log (customer_id, changed_at DESC);
